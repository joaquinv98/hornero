    private static Task SupportExtras(CoreHarness h) => h.Db(db => db.Database.ExecuteSqlRawAsync(
        """
        ALTER TABLE support.messages ADD COLUMN IF NOT EXISTS staff_id bigint;
        CREATE TABLE IF NOT EXISTS support.feedback (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id bigint NOT NULL REFERENCES support.tickets, rating integer NOT NULL,
          comment varchar(2000), staff_id bigint, imported boolean NOT NULL, created_at timestamptz NOT NULL);
        """));

    private static Task CouponTables(CoreHarness h) => h.Db(db => db.Database.ExecuteSqlRawAsync(
        """
        CREATE TABLE IF NOT EXISTS catalog.coupons (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, active boolean NOT NULL, code varchar(100) NOT NULL, currency character(3),
          existing_accounts_only boolean NOT NULL, expires_on date, kind varchar(32) NOT NULL, max_uses integer, new_accounts_only boolean NOT NULL,
          notes varchar(1000), once_per_account boolean NOT NULL, once_per_order boolean NOT NULL, recurring boolean NOT NULL, recurring_cycles integer,
          starts_on date, uses integer NOT NULL, value numeric(18,6) NOT NULL, product_ids bigint[] NOT NULL, cycles text[] NOT NULL);
        ALTER TABLE orders.orders ADD COLUMN IF NOT EXISTS coupon_id bigint;
        ALTER TABLE services.services ADD COLUMN IF NOT EXISTS coupon_id bigint;
        """));

    private static Task AffiliateTables(CoreHarness h) => h.Db(db => db.Database.ExecuteSqlRawAsync(
        """
        CREATE SCHEMA IF NOT EXISTS affiliates;
        CREATE TABLE IF NOT EXISTS affiliates.affiliates (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id bigint NOT NULL, code varchar(32) NOT NULL, created_at timestamptz NOT NULL,
          decided_at timestamptz, status varchar(32) NOT NULL);
        CREATE TABLE IF NOT EXISTS affiliates.clicks (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, affiliate_id bigint NOT NULL, at timestamptz NOT NULL, referrer_host varchar(255));
        CREATE TABLE IF NOT EXISTS affiliates.referrals (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id bigint NOT NULL, affiliate_id bigint NOT NULL, created_at timestamptz NOT NULL,
          order_id bigint, paid_before date, service_id bigint NOT NULL, source varchar(32) NOT NULL);
        CREATE TABLE IF NOT EXISTS affiliates.commissions (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, affiliate_id bigint NOT NULL, amount numeric(18,2) NOT NULL, base numeric(18,2) NOT NULL,
          created_at timestamptz NOT NULL, currency character(3) NOT NULL, document_id bigint, imported boolean NOT NULL, kind varchar(32) NOT NULL,
          rate numeric(18,4) NOT NULL, recurring boolean NOT NULL, referral_id bigint NOT NULL, release_on date NOT NULL, released_at timestamptz,
          reversed numeric(18,2) NOT NULL, reversed_at timestamptz, service_id bigint NOT NULL, status varchar(32) NOT NULL);
        CREATE TABLE IF NOT EXISTS affiliates.payouts (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, affiliate_id bigint NOT NULL, amount numeric(18,2) NOT NULL, credit_entry_id bigint,
          currency character(3) NOT NULL, decided_at timestamptz, details varchar(500), method varchar(32) NOT NULL, reason varchar(500),
          reference varchar(200), requested_at timestamptz NOT NULL, status varchar(32) NOT NULL);
        """));

    [TestMethod]
    public async Task RespuestasDelStaffYSatisfaccion_PorPersonaConElIndiceNetoYLosComentarios()
    {
        await using var h = await CoreHarness.Start();
        if (!await Exists(h, "support.feedback"))
        {
            Assert.AreEqual("SupportNotInstalled", (await Report(h, r => r.Satisfaction(OctoberToNovember, default))).Notes.Single().Key);
        }

        await SupportTables(h);
        await SupportExtras(h);
        await h.Db(async db =>
        {
            var ana = new StaffUser { Email = "ana@example.com", NormalizedEmail = "ANA@EXAMPLE.COM", Name = "Ana", SecurityStamp = "a", CreatedAt = DateTimeOffset.UtcNow };
            var beto = new StaffUser { Email = "beto@example.com", NormalizedEmail = "BETO@EXAMPLE.COM", Name = "Beto", SecurityStamp = "b", CreatedAt = DateTimeOffset.UtcNow };
            db.Set<StaffUser>().AddRange(ana, beto);
            await db.SaveChangesAsync();
            await db.Database.ExecuteSqlRawAsync(
                """
                INSERT INTO support.departments (id, name, hidden, clients_only, auto_reply, request_feedback, sort_order, mail_enabled, imap_port, imap_security, imap_uid_validity, imap_last_uid, created_at)
                VALUES (1, 'Soporte técnico', false, false, true, true, 1, false, 993, 'SslOnConnect', 0, 0, now());
                INSERT INTO support.tickets (id, number, requester_name, requester_email, cc, department_id, subject, status, priority, reply_token, merged_into_id, imported, created_at, last_message_at, updated_at, closed_at)
                SELECT id, 'T-' || id, 'Cliente', 'cliente@example.com', ARRAY[]::text[], 1, 'Consulta', 'Closed', 'Normal', 'token-' || id, NULL, false, '2026-10-01 12:00Z', '2026-10-01 12:00Z', '2026-10-01 12:00Z', NULL
                FROM generate_series(1, 5) id;
                INSERT INTO support.messages (ticket_id, author, author_name, body, internal, source, created_at, staff_id)
                SELECT ticket, author, name, 'Texto', internal, 'Portal', at::timestamptz, CASE who WHEN 'ana' THEN {0} WHEN 'beto' THEN {1} END
                FROM (VALUES
                  (1, 'Customer', 'Cliente', false, '2026-10-05 10:00Z', NULL),
                  (1, 'Staff', 'Ana', false, '2026-10-05 12:00Z', 'ana'), (1, 'Staff', 'Ana', true, '2026-10-05 12:30Z', 'ana'),
                  (2, 'Staff', 'Ana', false, '2026-10-20 12:00Z', 'ana'), (2, 'Staff', 'Beto', false, '2026-10-20 13:00Z', 'beto'),
                  (3, 'Staff', 'Beto', false, '2026-11-01 12:00Z', 'beto'),
                  (4, 'Staff', 'Carla (importado)', false, '2026-10-10 12:00Z', NULL),
                  (5, 'Staff', 'Ana', false, '2026-09-30 12:00Z', 'ana')) AS v(ticket, author, name, internal, at, who);
                INSERT INTO support.feedback (ticket_id, rating, comment, staff_id, imported, created_at)
                SELECT ticket, rating, comment, CASE who WHEN 'ana' THEN {0} WHEN 'beto' THEN {1} END, false, at::timestamptz
                FROM (VALUES
                  (1, 10, 'Excelente', 'ana', '2026-10-06 12:00Z'), (2, 9, NULL, 'ana', '2026-10-21 12:00Z'), (3, 4, 'Tardaron', 'beto', '2026-11-02 12:00Z'),
                  (4, 8, '', NULL, '2026-10-11 12:00Z'), (5, 2, 'Mal', 'ana', '2026-09-30 12:00Z')) AS v(ticket, rating, comment, who, at);
                """,
                ana.Id,
                beto.Id);
        });

        // Un mensaje importado sin persona va con el nombre que firmó. Las notas internas no son respuestas.
        var replies = (await Report(h, r => r.StaffReplies(OctoberToNovember, default))).Table("StaffReplies");
        CollectionAssert.AreEqual(new object?[] { "Ana", 2, 2, 1 }, replies.Rows[0]);
        CollectionAssert.AreEqual(new object?[] { "Beto", 2, 2, 0 }, replies.Rows[1]);
        CollectionAssert.AreEqual(new object?[] { "Carla (importado)", 1, 1, 0 }, replies.Rows[2]);
        CollectionAssert.AreEqual(new object?[] { null, 5L, null, 1L }, replies.Totals.Single(), "un ticket con dos personas no se cuenta dos veces");

        var satisfaction = await Report(h, r => r.Satisfaction(OctoberToNovember, default));

        var staff = satisfaction.Table("SatisfactionByStaff");
        CollectionAssert.AreEqual(new object?[] { "Ana", 2, 9.5m, 0, 0, 2, 100m }, staff.Rows[0]);
        CollectionAssert.AreEqual(new object?[] { "Beto", 1, 4.0m, 1, 0, 0, -100m }, staff.Rows[1]);
        CollectionAssert.AreEqual(new object?[] { null, 1, 8.0m, 0, 1, 0, 0m }, staff.Rows[2], "sin persona asignada");
        CollectionAssert.AreEqual(new object?[] { null, 4, 7.8m, 1, 1, 2, 25m }, staff.Totals.Single(), "el promedio y el índice de todas");
        var comments = satisfaction.Table("SatisfactionComments").Rows;
        Assert.HasCount(2, comments, "sin los vacíos ni los de septiembre");
        CollectionAssert.AreEqual(new object?[] { new DateOnly(2026, 11, 2), "T-3", "Beto", 4, "Tardaron" }, comments[0]);
        CollectionAssert.AreEqual(new object?[] { new DateOnly(2026, 10, 6), "T-1", "Ana", 10, "Excelente" }, comments[1]);
    }

    [TestMethod]
    public async Task CuponesYAfiliados_UsoDelPeriodoYComisionesPorMoneda()
    {
        await using var h = await CoreHarness.Start();
        if (!await Exists(h, "catalog.coupons"))
        {
            Assert.AreEqual("CouponsNotInstalled", (await Report(h, r => r.Coupons(OctoberToNovember, default))).Notes.Single().Key);
        }

        if (!await Exists(h, "affiliates.affiliates"))
        {
            Assert.AreEqual("AffiliatesNotInstalled", (await Report(h, r => r.Affiliates(OctoberToNovember, default))).Notes.Single().Key);
        }

        await CouponTables(h);
        await AffiliateTables(h);
        var usd = await UsdAccount(h);
        await h.Db(async db =>
        {
            var product = (await db.Plans.SingleAsync(p => p.Id == h.PlanId)).ProductId;
            var referred = new[] { new Account("Referida 1", "ref1@example.com", Currency.Ars, October), new Account("Referida 2", "ref2@example.com", Currency.Ars, October) };
            db.Accounts.AddRange(referred);
            await db.SaveChangesAsync();
            Order Placed(long account, DateTimeOffset at) => new(account, Currency.Ars, at) { Status = OrderStatus.Completed };
            var orders = new[]
            {
                Placed(h.AccountId, October), Placed(referred[0].Id, new(2026, 11, 1, 12, 0, 0, TimeSpan.Zero)), Placed(h.AccountId, new(2026, 9, 20, 12, 0, 0, TimeSpan.Zero)),
                Placed(referred[1].Id, new(2026, 11, 2, 12, 0, 0, TimeSpan.Zero)),
            };
            db.Orders.AddRange(orders);
            Service Service(long account, ServiceStatus status)
            {
                var s = new Service(account, product, new BillingCycle(CycleUnit.Month), Currency.Ars, 12100m, 1, October);
                s.ImportState(status, 1, status == ServiceStatus.Active ? new DateOnly(2026, 12, 1) : null, null, October, status == ServiceStatus.Terminated ? October : null);
                return s;
            }

            var services = new[] { Service(referred[0].Id, ServiceStatus.Active), Service(referred[1].Id, ServiceStatus.Terminated) };
            db.Services.AddRange(services);
            await db.SaveChangesAsync();
            await db.Database.ExecuteSqlRawAsync(
                """
                INSERT INTO catalog.coupons (id, active, code, currency, existing_accounts_only, kind, max_uses, new_accounts_only, once_per_account, once_per_order, recurring, uses, value, product_ids, cycles)
                VALUES (1, true, 'VERANO25', NULL, false, 'Percent', 100, false, false, false, false, 3, 25, '{{}}', '{{}}'),
                       (2, true, 'BIENVENIDA', 'ARS', false, 'Fixed', NULL, true, true, false, false, 1, 1000, '{{}}', '{{}}'),
                       (3, false, 'VIEJO', NULL, false, 'Percent', NULL, false, false, false, false, 0, 10, '{{}}', '{{}}');
                UPDATE orders.orders SET coupon_id = 1 WHERE id IN ({0}, {1}, {2});
                UPDATE orders.orders SET coupon_id = 2 WHERE id = {3};
                UPDATE services.services SET coupon_id = 1 WHERE id IN ({4}, {5});
                INSERT INTO affiliates.affiliates (id, account_id, code, created_at, status)
                VALUES (1, {6}, 'PEPE', '2026-01-01 12:00Z', 'Active'), (2, {7}, 'LUCAS', '2026-10-01 12:00Z', 'Pending');
                INSERT INTO affiliates.clicks (affiliate_id, at)
                VALUES (1, '2026-10-02 12:00Z'), (1, '2026-10-03 12:00Z'), (1, '2026-11-01 12:00Z'), (1, '2026-09-30 12:00Z'), (2, '2026-11-02 12:00Z');
                INSERT INTO affiliates.referrals (id, account_id, affiliate_id, created_at, service_id, source)
                VALUES (1, {8}, 1, '2026-10-05 12:00Z', {4}, 'Link'), (2, {9}, 1, '2026-10-06 12:00Z', {5}, 'Link');
                INSERT INTO affiliates.commissions (affiliate_id, amount, base, created_at, currency, imported, kind, rate, recurring, referral_id, release_on, reversed, service_id, status)
                SELECT 1, amount, amount, at::timestamptz, currency, false, 'Percent', 10, false, 1, '2026-12-01', reversed, {4}, status
                FROM (VALUES (1000, 0, '2026-10-10 12:00Z', 'ARS', 'Held'), (500, 500, '2026-11-01 12:00Z', 'ARS', 'Reversed'),
                             (2000, 0, '2026-08-01 12:00Z', 'ARS', 'Released'), (5, 0, '2026-11-02 12:00Z', 'USD', 'Held')) AS v(amount, reversed, at, currency, status);
                INSERT INTO affiliates.payouts (affiliate_id, amount, currency, decided_at, method, requested_at, status)
                VALUES (1, 2000, 'ARS', '2026-10-15 12:00Z', 'Transfer', '2026-10-14 12:00Z', 'Paid'), (1, 300, 'ARS', NULL, 'Transfer', '2026-11-02 12:00Z', 'Requested');
                """,
                orders[0].Id,
                orders[1].Id,
                orders[2].Id,
                orders[3].Id,
                services[0].Id,
                services[1].Id,
                h.AccountId,
                usd,
                referred[0].Id,
                referred[1].Id);
        });

        // El pedido de septiembre queda afuera del período y el servicio dado de baja no es de hoy.
        var coupons = (await Report(h, r => r.Coupons(OctoberToNovember, default))).Table("Coupons");
        CollectionAssert.AreEqual(new object?[] { "VERANO25", "ReportCouponKind.Percent", 25m, null, 3, 100, 2, 2, 1 }, coupons.Rows[0]);
        CollectionAssert.AreEqual(new object?[] { "BIENVENIDA", "ReportCouponKind.Fixed", 1000m, "ARS", 1, null, 1, 1, 0 }, coupons.Rows[1]);
        CollectionAssert.AreEqual(new object?[] { "VIEJO", "ReportCouponKind.Percent", 10m, null, 0, null, 0, 0, 0 }, coupons.Rows[2]);

        var affiliates = await Report(h, r => r.Affiliates(OctoberToNovember, default));

        var activity = affiliates.Table("AffiliateActivity");
        CollectionAssert.AreEqual(new object?[] { h.AccountId, "Cliente de prueba", "PEPE", "ReportAffiliateStatus.Active", 3, 2 }, activity.Rows[0]);
        CollectionAssert.AreEqual(new object?[] { usd, "Cuenta en dólares", "LUCAS", "ReportAffiliateStatus.Pending", 1, 0 }, activity.Rows[1]);

        // Lo revertido no suma, en espera es lo de hoy y lo pagado es lo del período.
        var commissions = affiliates.Table("AffiliateCommissions");
        Assert.HasCount(2, commissions.Rows);
        CollectionAssert.AreEqual(new object?[] { h.AccountId, "Cliente de prueba", "ARS", 2, 1000m, 1000m, 2000m }, commissions.Rows[0]);
        CollectionAssert.AreEqual(new object?[] { h.AccountId, "Cliente de prueba", "USD", 1, 5m, 5m, 0m }, commissions.Rows[1]);
    }
