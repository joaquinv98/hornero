    private static Task<bool> Exists(CoreHarness h, string table) =>
        h.Query(async db => (await db.Database.SqlQueryRaw<bool>("SELECT to_regclass({0}) IS NOT NULL AS \"Value\"", table).ToListAsync()).Single());

    private static Task DomainTables(CoreHarness h) => h.Db(db => db.Database.ExecuteSqlRawAsync(
        """
        CREATE SCHEMA IF NOT EXISTS domains;
        CREATE TABLE IF NOT EXISTS domains.domains (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id bigint NOT NULL REFERENCES accounts.accounts, name varchar(255) NOT NULL,
          registrar_instance_id bigint NOT NULL REFERENCES platform.module_instances, status varchar(32) NOT NULL, registered_on date, expires_on date,
          years integer NOT NULL, currency character(3) NOT NULL, recurring_amount numeric(18,2) NOT NULL, auto_renew boolean NOT NULL,
          dns_management boolean NOT NULL, email_forwarding boolean NOT NULL, id_protection boolean NOT NULL, nameservers jsonb NOT NULL,
          external_ids jsonb NOT NULL, payment_method varchar(100), next_due_date date, paid_through date, created_at timestamptz NOT NULL);
        """));

    private static Task PdfTable(CoreHarness h) => h.Db(db => db.Database.ExecuteSqlRawAsync(
        """
        CREATE TABLE IF NOT EXISTS billing.document_pdfs (
          document_id bigint PRIMARY KEY REFERENCES billing.documents, fiscal_document_id bigint NOT NULL REFERENCES fiscal.documents,
          file_name varchar(100) NOT NULL, content bytea NOT NULL, created_at timestamptz NOT NULL);
        """));

    [TestMethod]
    public async Task Dominios_PorEstadoRegistradorYTld_LosQueVencenYSusAvisos()
    {
        await using var h = await CoreHarness.Start();
        if (!await Exists(h, "domains.domains"))
        {
            Assert.AreEqual("DomainsNotInstalled", (await Report(h, r => r.Domains(default))).Notes.Single().Key);
            await DomainTables(h);
        }

        var usd = await UsdAccount(h);
        await h.Db(async db =>
        {
            var internetbs = new ModuleInstallation { Name = "internetbs", BaseUrl = "http://127.0.0.1:9/", CreatedAt = DateTimeOffset.UtcNow };
            var manual = new ModuleInstallation { Name = "manual", BaseUrl = "http://127.0.0.1:9/", CreatedAt = DateTimeOffset.UtcNow };
            db.ModuleInstallations.AddRange(internetbs, manual);
            await db.SaveChangesAsync();
            var registrar = new ModuleInstance { InstallationId = internetbs.Id, Name = "Internet.bs", CreatedAt = DateTimeOffset.UtcNow };
            var nic = new ModuleInstance { InstallationId = manual.Id, Name = "Manual NIC", CreatedAt = DateTimeOffset.UtcNow };
            db.ModuleInstances.AddRange(registrar, nic);
            await db.SaveChangesAsync();
            await db.Database.ExecuteSqlRawAsync(
                """
                INSERT INTO domains.domains (account_id, name, registrar_instance_id, status, expires_on, years, currency, recurring_amount, auto_renew,
                                             dns_management, email_forwarding, id_protection, nameservers, external_ids, paid_through, created_at)
                SELECT CASE WHEN owner = 'usd' THEN {1} ELSE {0} END, name, CASE WHEN registrar = 'nic' THEN {3} ELSE {2} END, status, expires::date, years,
                       currency, amount, renew, false, false, false, '[]', '{{}}', expires::date, now()
                FROM (VALUES
                  ('a', 'ejemplo.com.ar', 'nic', 'Active', '2026-11-20', 1, 'ARS', 9000, false),
                  ('a', 'tienda.com', 'ibs', 'Active', '2027-01-15', 1, 'USD', 15, true),
                  ('a', 'viejo.net', 'ibs', 'Grace', '2026-10-25', 1, 'USD', 15, false),
                  ('usd', 'lejano.com', 'ibs', 'Active', '2027-08-01', 2, 'USD', 30, true),
                  ('a', 'cancelado.com', 'ibs', 'Cancelled', '2026-01-01', 1, 'USD', 15, false),
                  ('a', 'pendiente.ar', 'nic', 'Pending', NULL, 1, 'ARS', 9000, false)) AS v(owner, name, registrar, status, expires, years, currency, amount, renew)
                """,
                h.AccountId,
                usd,
                registrar.Id,
                nic.Id);
            await db.Database.ExecuteSqlRawAsync(
                """
                INSERT INTO notifications.outbound_emails (account_id, created_at, culture, dedup_key, html, message_id, recipient, status, subject, template)
                SELECT {0}, at::timestamptz, 'es-AR', 'k-' || n, '<p></p>', 'm-' || n, 'cliente@example.com', status, subject, template
                FROM (VALUES
                  (1, '2026-10-20 12:00Z', 'Sent', 'El dominio ejemplo.com.ar vence pronto', 'domain-expiring'),
                  (2, '2026-11-01 02:00Z', 'Failed', 'El dominio viejo.net venció', 'domain-expired'),
                  (3, '2026-11-02 12:00Z', 'Pending', 'El dominio tienda.com vence pronto', 'domain-expiring'),
                  (4, '2026-11-02 12:00Z', 'Sent', 'Factura emitida', 'invoice-issued'),
                  (5, '2026-09-30 12:00Z', 'Sent', 'El dominio tienda.com vence pronto', 'domain-expiring')) AS v(n, at, status, subject, template)
                """,
                h.AccountId);
        });

        var report = await Report(h, r => r.Domains(default));

        Assert.IsEmpty(report.Notes);
        var statuses = report.Table("DomainsByStatus");
        CollectionAssert.AreEqual(new[] { "ReportDomainStatus.Pending", "ReportDomainStatus.Active", "ReportDomainStatus.Grace", "ReportDomainStatus.Cancelled" }, statuses.Rows.Select(r => (string)r[0]!).ToArray());
        CollectionAssert.AreEqual(new object?[] { "ReportDomainStatus.Active", 3, 2 }, statuses.Rows[1]);
        CollectionAssert.AreEqual(new object?[] { null, 6L, 2L }, statuses.Totals.Single());

        // El de dos años factura la mitad por año. El TLD es lo que sigue al primer punto.
        var registrars = report.Table("DomainsByRegistrar");
        Assert.HasCount(4, registrars.Rows);
        CollectionAssert.AreEqual(new object?[] { "Internet.bs", "com", "USD", 2, 0, 1, 30m }, registrars.Rows[0]);
        CollectionAssert.AreEqual(new object?[] { "Internet.bs", "net", "USD", 1, 0, 0, 0m }, registrars.Rows[1]);
        CollectionAssert.AreEqual(new object?[] { "Manual NIC", "ar", "ARS", 1, 0, 0, 0m }, registrars.Rows[2]);
        CollectionAssert.AreEqual(new object?[] { "Manual NIC", "com.ar", "ARS", 1, 1, 1, 9000m }, registrars.Rows[3]);

        var expiring = report.Table("DomainsExpiring");
        Assert.HasCount(3, expiring.Rows, "el de agosto queda lejos y los cancelados y pendientes no vencen");
        CollectionAssert.AreEqual(new object?[] { "viejo.net", h.AccountId, "Cliente de prueba", "ReportDomainStatus.Grace", new DateOnly(2026, 10, 25), -8, "Reports.No", new DateOnly(2026, 10, 25), "Internet.bs", "USD", 15m }, expiring.Rows[0]);
        CollectionAssert.AreEqual(new object?[] { "ejemplo.com.ar", h.AccountId, "Cliente de prueba", "ReportDomainStatus.Active", new DateOnly(2026, 11, 20), 18, "Reports.No", new DateOnly(2026, 11, 20), "Manual NIC", "ARS", 9000m }, expiring.Rows[1]);
        Assert.AreEqual(74, expiring.Rows[2][5]);
        Assert.AreEqual("Reports.Yes", expiring.Rows[2][6]);

        var notices = await Report(h, r => r.DomainNotices(OctoberToNovember, default));

        // El de las 23 del 31/10 en Buenos Aires es de octubre. La factura y el de septiembre no son de este reporte.
        var months = notices.Table("DomainNoticesByMonth");
        CollectionAssert.AreEqual(new object?[] { new DateOnly(2026, 10, 1), "ReportDomainNotice.Expiring", 1, 1, 0, 0, 0 }, months.Rows[0]);
        CollectionAssert.AreEqual(new object?[] { new DateOnly(2026, 10, 1), "ReportDomainNotice.Expired", 1, 0, 0, 0, 1 }, months.Rows[1]);
        CollectionAssert.AreEqual(new object?[] { new DateOnly(2026, 11, 1), "ReportDomainNotice.Expiring", 1, 0, 1, 0, 0 }, months.Rows[2]);
        CollectionAssert.AreEqual(new object?[] { null, null, 3L, 1L, 1L, 0L, 1L }, months.Totals.Single());
        var detail = notices.Table("DomainNotices");
        Assert.HasCount(3, detail.Rows);
        CollectionAssert.AreEqual(
            new object?[] { new DateOnly(2026, 10, 31), h.AccountId, "Cliente de prueba", "ReportDomainNotice.Expired", "cliente@example.com", "El dominio viejo.net venció", "ReportEmailStatus.Failed" },
            detail.Rows[1]);
    }

    [TestMethod]
    public async Task PdfPorLote_LosDelMesEnUnZip_YLosQueTodaviaNoTienen()
    {
        await using var h = await CoreHarness.Start();
        var november = new DateOnly(2026, 11, 1);
        if (!await Exists(h, "billing.document_pdfs"))
        {
            Assert.AreEqual("PdfNotInstalled", (await Report(h, r => r.InvoicePdfs(november, default))).Notes.Single().Key);
            Assert.IsNull(await Report(h, r => r.InvoicePdfZip(november, default)));
            await PdfTable(h);
        }

        var issuer = await Issuer(h);
        var first = (await Order(h)).InvoiceId!.Value;
        var second = (await Order(h)).InvoiceId!.Value;
        var note = await CreditNote(h, second);
        long noteNumber = 0;
        await h.Db(async db =>
        {
            var invoiceVoucher = Voucher(issuer, first, 6, 1, new DateOnly(2026, 11, 2), "{}");
            var noteVoucher = Voucher(issuer, note, 8, 1, new DateOnly(2026, 11, 2), "{}");
            db.FiscalDocuments.AddRange(invoiceVoucher, noteVoucher);
            await db.SaveChangesAsync();
            await db.Database.ExecuteSqlRawAsync(
                "INSERT INTO billing.document_pdfs (document_id, fiscal_document_id, file_name, content, created_at) VALUES ({0}, {1}, 'comprobante.pdf', {4}, now()), ({2}, {3}, 'comprobante.pdf', {5}, now())",
                first,
                invoiceVoucher.Id,
                note,
                noteVoucher.Id,
                "%PDF-factura"u8.ToArray(),
                "%PDF-nota"u8.ToArray());
            noteNumber = (await db.Documents.SingleAsync(d => d.Id == note)).Number!.Value;
        });

        var report = await Report(h, r => r.InvoicePdfs(november, default));

        // La segunda factura todavía no tiene comprobante, así que tampoco PDF.
        var table = report.Table("InvoicePdfs");
        CollectionAssert.AreEqual(new object?[] { "DocumentKind.Invoice", 2, 1, 1 }, table.Rows[0]);
        CollectionAssert.AreEqual(new object?[] { "DocumentKind.CreditNote", 1, 1, 0 }, table.Rows[1]);
        CollectionAssert.AreEqual(new object?[] { null, 3L, 2L, 1L }, table.Totals.Single());
        Assert.AreEqual("1", report.Notes.Single(n => n.Key == "PdfMissing").Args.Single());

        // Dos archivos con el mismo nombre: el segundo lleva su número adelante.
        var zip = await Report(h, r => r.InvoicePdfZip(november, default));
        using var archive = new ZipArchive(new MemoryStream(zip!), ZipArchiveMode.Read);
        CollectionAssert.AreEqual(new[] { "comprobante.pdf", string.Create(CultureInfo.InvariantCulture, $"{noteNumber}-comprobante.pdf") }, archive.Entries.Select(e => e.FullName).ToArray());
        using var reader = new StreamReader(archive.Entries[0].Open());
        Assert.AreEqual("%PDF-factura", await reader.ReadToEndAsync());
        var october = await Report(h, r => r.InvoicePdfs(new DateOnly(2026, 10, 1), default));
        Assert.IsEmpty(october.Table("InvoicePdfs").Rows);
    }
